/**
 * The Windows installer template, src-tauri/installer/installer.nsi
 * (tauri.conf.json → bundle.windows.nsis.template).
 *
 * It is Tauri's own NSIS template for the @tauri-apps/cli version in
 * package-lock.json, plus the CoreTools patches below — never edited by hand:
 *
 *   node scripts/installer-template.mjs           check: the file is exactly
 *                                                 upstream + PATCHES (CI)
 *   node scripts/installer-template.mjs --update  regenerate it (after a
 *                                                 @tauri-apps/cli bump)
 *
 * Why patch at all: installing a newer CoreTools over an older one runs the
 * old version's uninstaller. Tauri runs it with its full window — including
 * "Delete the application data", which erases the vault (Authenticator
 * accounts, saved logins) — unless the installer itself was started by an
 * auto-updater. People updating by hand ticked it and lost their data. Every
 * Tauri uninstaller, including ones already installed, understands /UPDATE
 * (never delete app data, keep shortcuts) and /P (passive: no window), so
 * the fix lives in the NEW installer and protects the very next update.
 *
 * If an anchor below is missing after a CLI bump, upstream changed that part
 * of the template: re-read it and adapt the patch, don't force it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src-tauri", "installer", "installer.nsi");

const PATCHES = [
  {
    // Ask to close CoreTools before replacing it (the passive uninstaller
    // below would close it without asking). Cancel stays on this page.
    find: "  reinst_uninstall:\n    HideWindow\n",
    replace:
      "  reinst_uninstall:\n" +
      "    ; CoreTools patch (scripts/installer-template.mjs): close the running app first,\n" +
      "    ; with the user's OK, since the previous version's uninstaller runs passively.\n" +
      '    !insertmacro CheckIfAppIsRunning "${MAINBINARYNAME}.exe" "${PRODUCTNAME}"\n' +
      "    HideWindow\n",
  },
  {
    // Removing the previous version is always part of installing this one:
    // run its uninstaller as an update, so it keeps the user's data and
    // never shows the "Delete the application data" choice.
    find:
      '      ${IfThen} $UpdateMode = 1 ${|} StrCpy $R1 "$R1 /UPDATE" ${|} ; append /UPDATE\n' +
      '      ${IfThen} $PassiveMode = 1 ${|} StrCpy $R1 "$R1 /P" ${|} ; append /P\n',
    replace:
      "      ; CoreTools patch (scripts/installer-template.mjs): the previous version is\n" +
      "      ; removed as part of installing this one, so always as an update (/UPDATE:\n" +
      "      ; app data and shortcuts kept) and without its window (/P: no \"Delete the\n" +
      "      ; application data\" choice). Upstream adds these only for auto-updates.\n" +
      '      StrCpy $R1 "$R1 /UPDATE /P"\n',
  },
];

function cliVersion() {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  const version = lock.packages?.["node_modules/@tauri-apps/cli"]?.version;
  if (!/^\d+\.\d+\.\d+$/.test(version ?? "")) throw new Error("No @tauri-apps/cli version in package-lock.json");
  return version;
}

async function upstream(version) {
  const url =
    `https://raw.githubusercontent.com/tauri-apps/tauri/tauri-cli-v${version}` +
    "/crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi";
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Couldn't fetch the upstream template (${response.status}): ${url}`);
  return (await response.text()).replace(/\r\n/g, "\n");
}

function patched(source, version) {
  let text = source;
  for (const { find, replace } of PATCHES) {
    const at = text.indexOf(find);
    if (at < 0 || text.indexOf(find, at + 1) >= 0) {
      throw new Error(
        `Upstream template for tauri-cli ${version} no longer has exactly one:\n${find}\n` +
          "Re-read it and adapt PATCHES in scripts/installer-template.mjs.",
      );
    }
    text = text.replace(find, replace);
  }
  return (
    `; Generated by scripts/installer-template.mjs from Tauri's NSIS template (tauri-cli v${version}).\n` +
    "; Do not edit by hand: change PATCHES there and run it with --update.\n" +
    text
  );
}

const update = process.argv.includes("--update");
const version = cliVersion();
const expected = patched(await upstream(version), version);

if (update) {
  writeFileSync(target, expected);
  console.log(`installer.nsi regenerated from tauri-cli v${version} + ${PATCHES.length} patches.`);
} else {
  let actual = "";
  try {
    actual = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // Missing: reported below.
  }
  if (actual !== expected) {
    const message =
      `src-tauri/installer/installer.nsi isn't Tauri's template for tauri-cli v${version} plus the ` +
      "CoreTools patches — run: node scripts/installer-template.mjs --update";
    console.error(process.env.GITHUB_ACTIONS ? `::error::${message}` : message);
    process.exit(1);
  }
  console.log(`installer.nsi = tauri-cli v${version} template + ${PATCHES.length} CoreTools patches ✓`);
}
